/**
 * The compiler (M15).
 *
 * `bv compile <runId> --out flows/x.spec.ts` turns a recorded run into a
 * plain Playwright TypeScript script.
 *
 * The script is meant to be **read by a human**. That is the point: a
 * compiled flow is something you can put in a pull request, review, and
 * run in CI without any of browser-verified's machinery. The best locator
 * comes first; the fallbacks are in comments, so a human can see what the
 * alternatives were and pick one deliberately.
 */
import { applyVariables, findVariables, type CompiledFlow, type RecordedRun, type RecordedStep } from './ir.js';

/**
 * Compile a recorded run into a flow.
 *
 * The variables are found first, so a value used more than once becomes a
 * parameter rather than being written out twice.
 */
export function compileFlow(run: RecordedRun, name = 'flow'): CompiledFlow {
  const variables = findVariables(run);
  const steps = applyVariables(run.steps, variables);
  return {
    name,
    steps,
    variables,
    ...(run.goal !== undefined ? { goal: run.goal } : {}),
  };
}

/**
 * Render a flow as a Playwright TypeScript script.
 *
 * The output is deliberately plain: `import { test, expect } from
 * '@playwright/test'` and a `test(...)` block. Nothing from
 * browser-verified is imported, so the script runs in any Playwright
 * project.
 */
export function renderScript(flow: CompiledFlow): string {
  const lines: string[] = [];

  lines.push('// Generated by browser-verified. Compiled from a recorded run.');
  if (flow.goal !== undefined) {
    lines.push(`// Goal: ${flow.goal}`);
  }
  lines.push('//');
  lines.push('// This script is plain Playwright: it needs no browser-verified code.');
  lines.push('// Review it, put it in version control, and run it in CI.');
  lines.push('');
  lines.push("import { test, expect, type Page, type Locator } from '@playwright/test';");
  lines.push('');

  if (flow.variables.length > 0) {
    lines.push('/** The parameters this flow takes. */');
    lines.push('interface FlowVars {');
    for (const variable of flow.variables) {
      lines.push(`  /** Default: ${JSON.stringify(variable.defaultValue)} */`);
      lines.push(`  ${variable.name}: string;`);
    }
    lines.push('}');
    lines.push('');
  }

  lines.push('/** Find an element, trying the recorded locators in order. */');
  lines.push('async function findElement(page: Page, selectors: string[]): Promise<Locator> {');
  lines.push('  for (const selector of selectors) {');
  lines.push('    try {');
  lines.push('      const locator = resolve(page, selector);');
  lines.push('      if (await locator.count() > 0) return locator.first();');
  lines.push('    } catch {');
  lines.push('      // This selector does not apply here; try the next one.');
  lines.push('    }');
  lines.push('  }');
  lines.push('  throw new Error(`no element matched any of: ${selectors.join(", ")}`);');
  lines.push('}');
  lines.push('');

  lines.push('/** Resolve one recorded selector. */');
  lines.push('function resolve(page: Page, selector: string): Locator {');
  lines.push("  if (selector.startsWith('role=')) {");
  lines.push('    const match = /^role=(\\S+)(?: name="(.*)")?$/.exec(selector);');
  lines.push('    if (match === null) throw new Error(`bad selector: ${selector}`);');
  lines.push('    const [, role, name] = match;');
  lines.push('    return page.getByRole(role as Parameters<Page["getByRole"]>[0], name !== undefined ? { name } : {});');
  lines.push('  }');
  lines.push("  if (selector.startsWith('label=')) {");
  lines.push('    return page.getByLabel(selector.slice(6).replace(/^"|"$/g, ""));');
  lines.push('  }');
  lines.push("  if (selector.startsWith('text=')) {");
  lines.push('    return page.getByText(selector.slice(5).replace(/^"|"$/g, ""));');
  lines.push('  }');
  lines.push("  if (selector.startsWith('testid=')) {");
  lines.push('    return page.getByTestId(selector.slice(8));');
  lines.push('  }');
  lines.push('  return page.locator(selector);');
  lines.push('}');
  lines.push('');

  lines.push("test('" + escapeSingle(flow.name) + "', async ({ page }) => {");

  if (flow.variables.length > 0) {
    lines.push('  const vars: FlowVars = {');
    for (const variable of flow.variables) {
      lines.push(`    ${variable.name}: process.env.${variable.name.toUpperCase()} ?? ${JSON.stringify(variable.defaultValue)},`);
    }
    lines.push('  };');
    lines.push('');
  }

  for (const step of flow.steps) {
    lines.push(...renderStep(step, flow));
  }

  lines.push('});');
  lines.push('');

  return lines.join('\n');
}

/** Render one step as script lines. */
function renderStep(step: RecordedStep, flow: CompiledFlow): string[] {
  const lines: string[] = [];
  const selectors = step.locators.map((candidate) => candidate.value);

  // A comment naming the step and listing the fallbacks.
  lines.push(`  // Step ${step.index}: ${step.kind}`);
  if (selectors.length > 1) {
    lines.push(`  // Fallback locators, in the order they were tried:`);
    for (const candidate of step.locators.slice(1)) {
      lines.push(`  //   ${candidate.value}`);
    }
  }

  switch (step.kind) {
    case 'goto':
      lines.push(`  await page.goto(${JSON.stringify(step.params.value ?? step.pre.url)});`);
      break;

    case 'click':
    case 'dblclick':
    case 'hover': {
      const method = step.kind === 'dblclick' ? 'dblclick' : step.kind;
      lines.push(`  const target${step.index} = await findElement(page, ${JSON.stringify(selectors)});`);
      lines.push(`  await target${step.index}.${method}();`);
      break;
    }

    case 'fill':
    case 'type': {
      const value = renderValue(step.params.value, flow);
      lines.push(`  const target${step.index} = await findElement(page, ${JSON.stringify(selectors)});`);
      lines.push(`  await target${step.index}.fill(${value});`);
      break;
    }

    case 'select': {
      lines.push(`  const target${step.index} = await findElement(page, ${JSON.stringify(selectors)});`);
      lines.push(`  await target${step.index}.selectOption(${JSON.stringify(step.params.option ?? '')});`);
      break;
    }

    case 'check':
    case 'uncheck': {
      lines.push(`  const target${step.index} = await findElement(page, ${JSON.stringify(selectors)});`);
      lines.push(`  await target${step.index}.${step.kind}();`);
      break;
    }

    case 'press': {
      lines.push(`  const target${step.index} = await findElement(page, ${JSON.stringify(selectors)});`);
      lines.push(`  await target${step.index}.press(${JSON.stringify(step.params.key ?? 'Enter')});`);
      break;
    }

    case 'upload': {
      lines.push(`  const target${step.index} = await findElement(page, ${JSON.stringify(selectors)});`);
      lines.push(`  await target${step.index}.setInputFiles(${JSON.stringify(step.params.file ?? '')});`);
      break;
    }

    case 'scroll': {
      lines.push(`  await page.mouse.wheel(0, ${step.params.amount ?? 0});`);
      break;
    }

    case 'wait': {
      lines.push(`  await target${step.index}.waitFor({ state: '${step.params.condition ?? 'visible'}' });`);
      break;
    }

    default:
      break;
  }

  // The inferred assertions.
  for (const assertion of step.assertions) {
    lines.push(...renderAssertion(assertion, step));
  }

  lines.push('');
  return lines;
}

/** Render an inferred assertion as script lines. */
function renderAssertion(
  assertion: { kind: string; description: string; value?: string; count?: number },
  step: RecordedStep,
): string[] {
  switch (assertion.kind) {
    case 'url_changed':
      return [`  await expect(page).toHaveURL(${JSON.stringify(assertion.value ?? '')});`];
    case 'text_added':
      return [`  await expect(page.getByText(${JSON.stringify(assertion.value ?? '')})).toBeVisible();`];
    case 'count_changed':
      return [
        `  await expect(page.locator(${JSON.stringify(step.locators[0]?.value ?? '')})).toHaveCount(${assertion.count ?? 0});`,
      ];
    case 'dialog_appeared':
      return [`  // A ${assertion.value ?? 'dialog'} dialog was expected here.`];
    case 'popup_appeared':
      return [`  // A popup was expected at ${assertion.value ?? '?'}.`];
    default:
      return [];
  }
}

/**
 * Render a value, turning a `{{var}}` slot into a reference to the variable.
 */
function renderValue(value: string | undefined, flow: CompiledFlow): string {
  if (value === undefined) return "''";
  const match = /^\{\{(\w+)\}\}$/.exec(value);
  if (match !== null) {
    const name = match[1] ?? '';
    const variable = flow.variables.find((v) => v.name === name);
    if (variable !== undefined) return `vars.${variable.name}`;
  }
  return JSON.stringify(value);
}

/** Escape a string for a single-quoted JavaScript literal. */
function escapeSingle(value: string): string {
  return value.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}
